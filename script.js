function displaySurahs(data) {
    const container = document.getElementById('surahContainer');
    container.innerHTML = '';

    data.forEach(item => {
        let eventsList = item.events.map(e => `<li>${e}</li>`).join('');

        const card = document.createElement('div');
        card.className = 'card';
        card.innerHTML = `
            <div class="card-header">
                <span class="surah-title">سورة ${item.name}</span>
                <span class="surah-num">نمبر ${item.num}</span>
            </div>
            <div class="meaning"><strong>معنی / ترجمہ:</strong> ${item.meaning}</div>
            <div class="revelation"><strong>شانِ نزول:</strong> ${item.revelation}</div>
            
            <div class="section-title">اہم واقعات:</div>
            <ul class="events-list">
                ${eventsList}
            </ul>

            <div class="section-title">پورا پس منظر:</div>
            <div class="background-text">${item.background}</div>
        `;
        container.appendChild(card);
    });
}

function searchSurah() {
    const query = document.getElementById('searchInput').value.trim().toLowerCase();
    const filtered = surahData.filter(item => 
        item.name.toLowerCase().includes(query) || 
        item.num.toString().includes(query)
    );
    displaySurahs(filtered);
}

